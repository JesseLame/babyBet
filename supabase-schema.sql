-- Baby Bet Board schema for Supabase
-- This project now uses a single shared list. The `board_key` columns remain
-- for compatibility with existing data and older rows.
-- If you want stricter protection later, add RLS policies on top of this schema.

create table if not exists public.baby_bet_bets (
  id text primary key,
  board_key text not null,
  created_at timestamptz not null default now(),
  predicted_date text not null default '',
  predicted_name text not null default '',
  guessed_by text not null default '',
  guess_time text not null default '',
  actual_date text not null default '',
  actual_name text not null default '',
  result_note text not null default ''
);

create index if not exists baby_bet_bets_board_key_created_at_idx
  on public.baby_bet_bets (board_key, created_at desc);

alter table if exists public.baby_bet_bets
  add column if not exists guessed_by text not null default '',
  add column if not exists guess_time text not null default '';

alter table if exists public.baby_bet_bets
  drop column if exists prediction_note,
  drop column if exists stake;

alter table if exists public.baby_bet_bets enable row level security;

drop policy if exists "Public read baby bet bets" on public.baby_bet_bets;
create policy "Public read baby bet bets"
  on public.baby_bet_bets
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public write baby bet bets" on public.baby_bet_bets;
create policy "Public write baby bet bets"
  on public.baby_bet_bets
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public update baby bet bets" on public.baby_bet_bets;
create policy "Public update baby bet bets"
  on public.baby_bet_bets
  for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Public delete baby bet bets" on public.baby_bet_bets;
create policy "Public delete baby bet bets"
  on public.baby_bet_bets
  for delete
  to anon, authenticated
  using (true);

